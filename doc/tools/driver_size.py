"""Generate the persona platform headers and the driver code-size table.

    python3 doc/tools/driver_size.py            # print the table
    python3 doc/tools/driver_size.py --update   # rewrite the headers and the table
    python3 doc/tools/driver_size.py --check    # exit 1 if one of them is stale

The table sits between two marker lines of doc/driver_guide.md:

    <!-- driver_size:begin table -->
    ...
    <!-- driver_size:end table -->

It needs riscv-none-elf-gcc on the PATH (RISCV_CC=<compiler> for another): it is
not part of the checks that run without a cross compiler. Run --update after
a change to the driver (sw/src, sw/include) or to a persona (rtl_configs.py).
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
GUIDE = ROOT / "doc" / "driver_guide.md"
SW = ROOT / "sw"
HDR_DIR = SW / "include" / "persona"
sys.path.insert(0, str(ROOT / "sim" / "rtl_sim" / "bin"))
from rtl_configs import PERSONAS                               # noqa: E402

CC = os.environ.get("RISCV_CC", "riscv-none-elf-gcc")      # RISCV_CC=<compiler> for another
SIZE = CC[:-3] + "size" if CC.endswith("gcc") else "riscv-none-elf-size"
FLAGS = ["-Os", "-march=rv32emc_zbb_zba_zbs_zicsr_zcb", "-mabi=ilp32e", "-ffunction-sections"]
SRCS = ["belenos.c", "blns_gpu.c", "blns_dpi.c", "blns_dbi.c", "blns_ddc.c", "blns_hotplug.c"]

# Belenos parameters -> platform-header feature (sw/include/belenos_hw.h), the
# features a persona sets. The display driver (DPI, DBI) and the HDMI options
# (DPI_DDC, DPI_ISLAND, DPI_AUDIO) follow DIF_TYPE and the DPI_* parameters,
# which belong to the SoC and its panel, not to the persona: left undefined.
FEATURES = [
    ("GPU",          lambda p: p["GPU_EN"]),
    ("GPU_XY",       lambda p: p["GPU_EN"] and p["GPU_XY_EN"]),
    ("GPU_GRAD",     lambda p: p["GPU_EN"] and p["GPU_GRAD_EN"]),
    ("GPU_BLEND",    lambda p: p["GPU_EN"] and p["GPU_BLEND_EN"]),
    ("GPU_TRI",      lambda p: p["GPU_EN"] and p["GPU_XY_EN"] and p["GPU_TRI_EN"]),
    ("GPU_REMAP",    lambda p: p["GPU_EN"] and p["GPU_REMAP_EN"]),
    ("GPU_MPLANE",   lambda p: p["GPU_EN"] and p["GPU_MPLANE_EN"]),
    ("GPU_IMM",      lambda p: p["GPU_EN"] and p["GPU_IMM_EN"]),
    ("GPU_LINE",     lambda p: p["GPU_EN"] and p["GPU_XY_EN"] and p["GPU_LINE_EN"]),
    ("GPU_BILINEAR", lambda p: p["GPU_EN"] and p["GPU_XY_EN"] and p.get("GPU_BILINEAR_EN", 0)),
    ("LUT",          lambda p: p["LUT_EN"]),
    ("LUT2",         lambda p: p["LUT_EN"] and p["LUT_BANKS"] == 2),
    ("CURSOR",       lambda p: p.get("CURSOR_EN", 1)),
]

BANNER = """/*----------------------------------------------------------------------------
 *          _    _           Family:    aRVern Graphic Controller
 *         / \\__/ \\          File:      {name}
 *        /   /\\   \\         --------------------------------------------
 *    ===/   /=========      Copyright: (c) 2026, aRVern-dev
 *      /   / RV \\   \\       Contact:   arvernsilicon@gmail.com
 *     /___/______\\___\\      GitHub:    https://github.com/Arvern-Silicon
 *
 * SPDX-License-Identifier: BSD-3-Clause
 * Full license text is available in the LICENSE file at the repository root.
 *----------------------------------------------------------------------------
 * Platform header of the {persona} persona (sw/include/belenos_hw.h): the
 * optional features its build has (1) and leaves out (0), from the persona's
 * parameters (sim/rtl_sim/bin/rtl_configs.py PERSONAS). Generated by
 * doc/tools/driver_size.py --update: do not edit.
 *
 * The display driver and the HDMI options (BLNS_HW_DPI, _DBI, _DPI_DDC,
 * _DPI_ISLAND, _DPI_AUDIO) follow DIF_TYPE and the DPI parameters, the SoC's
 * choice: not stated here (run-time detection). A board names its own header,
 * which includes this one and states them:
 *
 *     #include "persona/{name}"
 *     #define BLNS_HW_DPI 1
 *     #define BLNS_HW_DBI 0
 *----------------------------------------------------------------------------*/
"""


def header_text(persona, params):
    name = f"blns_{persona}.h"
    guard = f"BLNS_PERSONA_{persona.upper()}_H"
    lines = [BANNER.format(name=name, persona=persona).rstrip("\n"),
             f"#ifndef {guard}", f"#define {guard}", ""]
    for f, fn in FEATURES:
        lines.append(f"#define BLNS_HW_{f:<13s}{1 if fn(params) else 0}")
    lines += ["", f"#endif /* {guard} */"]
    return "\n".join(lines) + "\n"


def headers():
    return {HDR_DIR / f"blns_{p}.h": header_text(p, d) for p, d in PERSONAS}


def sizes(hdrs):
    """{label: {source: text + data + bss}} for no header and each persona's"""
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for path, text in hdrs.items():                         # the headers as generated
            (tmp / "persona").mkdir(exist_ok=True)
            (tmp / "persona" / path.name).write_text(text)
        rows = [("none", [])] + [(p, ["-DBLNS_PLATFORM_HEADER=\"persona/blns_%s.h\"" % p, f"-I{tmp}"])
                                 for p, _ in PERSONAS]
        for label, defs in rows:
            objs = []
            for s in SRCS:
                o = tmp / f"{label}_{s[:-2]}.o"
                subprocess.run([CC, *FLAGS, *defs, f"-I{SW / 'include'}", "-c", str(SW / "src" / s),
                                "-o", str(o)], check=True)
                objs.append(o)
            res = subprocess.run([SIZE, *map(str, objs)], check=True, capture_output=True, text=True).stdout
            vals = [list(map(int, ln.split()[:3])) for ln in res.splitlines()[1:] if ln.strip()]
            if any(v[1] or v[2] for v in vals):
                raise SystemExit("driver_size: a driver object has data or bss: the table states none")
            out[label] = {s: v[0] for s, v in zip(SRCS, vals)}
    return out


def fmt(n):
    return f"{n:,}".replace(",", " ")                          # thousands as the guides write them


def table(sz):
    ver = subprocess.run([CC, "-dumpversion"], check=True, capture_output=True, text=True).stdout.strip()
    head = "| Platform header | " + " | ".join(f"`{s}`" for s in SRCS) + " | Total |"
    lines = [f"Bytes of each driver object (text; none has data or bss), with `{Path(CC).name}` {ver},",
             f"`{' '.join(FLAGS)}`:", "",
             head, "|---|" + "---:|" * (len(SRCS) + 1)]
    for label, row in sz.items():
        name = "none (run-time detection)" if label == "none" else f"{label} (`persona/blns_{label}.h`)"
        lines.append(f"| {name} | " + " | ".join(fmt(row[s]) for s in SRCS) + f" | {fmt(sum(row.values()))} |")
    return "\n".join(lines)


def rewrite(text, body):
    pat = re.compile(r"(<!-- driver_size:begin table -->\n)(.*?)(\n<!-- driver_size:end table -->)", re.S)
    if len(pat.findall(text)) != 1:
        raise SystemExit(f"driver_size: want one table marker pair in {GUIDE.name}")
    return pat.sub(lambda m: m.group(1) + "\n" + body + "\n" + m.group(3), text)


def main(argv):
    hdrs = headers()
    body = table(sizes(hdrs))
    if not argv:
        print(body)
        return 0
    if argv[0] not in ("--check", "--update"):
        print(__doc__)
        return 2
    stale = []
    for path, text in sorted(hdrs.items()):
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if argv[0] == "--update":
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for path in sorted(set(HDR_DIR.glob("blns_*.h")) - set(hdrs)):
        stale.append(path)                                     # a persona no longer in rtl_configs
        if argv[0] == "--update":
            path.unlink()
    old = GUIDE.read_text()
    new = rewrite(old, body)
    if new != old:
        stale.append(GUIDE)
        if argv[0] == "--update":
            GUIDE.write_text(new)
    for path in stale:
        rel = path.relative_to(ROOT)
        print(f"driver_size: {rel} is stale: run doc/tools/driver_size.py --update" if argv[0] == "--check"
              else f"driver_size: updated {rel}")
    if not stale:
        print("driver_size: up to date")
    return 1 if argv[0] == "--check" and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
